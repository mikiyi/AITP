-- =====================================================================
-- AITP 迁移 041：内部调度类提示词的调用计数
--   能力类提示词（用例生成、缺陷分析…）每次调用都会写 biz_ai_record，
--   提示词库按 prompt_code 统计就够用。
--   但智能路由、知识库问答助手、自动整理这几条模板跑在「幕后」：
--   把它们塞进 AI 执行记录会让列表被路由噪声淹没，所以此前一次都没被统计到，
--   卡片永远显示「用过 0 次」。这里给它们单独记一笔累计次数。
--   一个 code 一行，UPSERT 累加；升级前的历史调用没有留痕，从本次升级起算。
-- =====================================================================

CREATE TABLE IF NOT EXISTS sys_prompt_usage (
    prompt_code   TEXT PRIMARY KEY,
    use_count     INTEGER NOT NULL DEFAULT 0,
    last_used_at  TEXT NOT NULL
);
